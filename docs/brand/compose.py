#!/usr/bin/env python3
"""Writes the composed brand artwork in src/ from the mark and the tokens below.

The mark (src/logo.svg, logo-small.svg, logo-mono.svg) is drawn by hand. The
banners, social cards and lockups are composed from it here, in a dark and a
light version, so they always use the same mark, colours and type:

    python3 docs/brand/compose.py      then    python3 docs/brand/build.py

Text stays live SVG text (Ubuntu Sans for words, Fira Code for keys), so edit
the strings here; build.py renders them with the fonts installed.
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "src"

TAGLINE = "The on-screen keyboard for people who write code."
CHIPS = ["Rust", "Ubuntu", "Android", "Tiếng Việt", "MIT / Apache-2.0"]
REPO = "github.com/tristanseltec/super-keyboard"

UI_FONT = "'Ubuntu Sans', 'Noto Sans', sans-serif"
CODE_FONT = "'Fira Code', 'Ubuntu Sans Mono', 'DejaVu Sans Mono', monospace"

# Colour tokens; docs/BRAND.md lists them.
THEMES = {
    "dark": dict(
        bg="#16161e", glow1="#7aa2f7", glow2="#bb9af7", glow_op="0.22",
        title="#e3e8ff", text="#a9b1d6", muted="#737aa2",
        key_top="#2a2f45", key_bot="#1f2335", skirt="#0f1017", key_text="#c0caf5",
        border="#3b4261", chip_bg="#24283b", dot="#ffffff", dot_op="0.05",
    ),
    "light": dict(
        bg="#f5f6fb", glow1="#7aa2f7", glow2="#bb9af7", glow_op="0.20",
        title="#1a1b26", text="#3b4261", muted="#6172b0",
        key_top="#ffffff", key_bot="#f1f3fa", skirt="#cfd5e8", key_text="#343b58",
        border="#d5d9e8", chip_bg="#e6e9f5", dot="#1a1b26", dot_op="0.06",
    ),
}
ACCENT, ACCENT_SKIRT, INK = "#ff9e64", "#c76a35", "#1a1b26"

MARK = (SRC / "logo.svg").read_text()
MARK_DEFS = MARK.split("<defs>")[1].split("</defs>")[0]
MARK_BODY = MARK.split("</defs>")[1].split("</svg>")[0]


def mark(x, y, size):
    return f'  <g transform="translate({x} {y}) scale({size / 512})">{MARK_BODY}</g>\n'


def keycap(x, y, label, t, rot=0, accent=False, font=44, size=118):
    """One key, tilted by `rot` degrees, as on the keyboard."""
    r = size * 0.2
    top = ACCENT if accent else "url(#keytop)"
    family = UI_FONT if label == "ệ" else CODE_FONT
    return f"""  <g transform="translate({x} {y}) rotate({rot})">
    <rect x="{-size / 2}" y="{-size / 2 + 9}" width="{size}" height="{size}" rx="{r}" fill="{ACCENT_SKIRT if accent else t['skirt']}"/>
    <rect x="{-size / 2}" y="{-size / 2}" width="{size}" height="{size}" rx="{r}" fill="{top}" stroke="{ACCENT if accent else t['border']}" stroke-width="2"/>
    <text x="0" y="{font * 0.36}" text-anchor="middle" font-family="{family}" font-size="{font}" font-weight="600" fill="{INK if accent else t['key_text']}">{label}</text>
  </g>
"""


def background(w, h, t):
    return f"""  <defs>
    <radialGradient id="glowA" cx="0.12" cy="0.05" r="0.75">
      <stop offset="0" stop-color="{t['glow1']}" stop-opacity="{t['glow_op']}"/>
      <stop offset="1" stop-color="{t['glow1']}" stop-opacity="0"/>
    </radialGradient>
    <radialGradient id="glowB" cx="0.95" cy="1" r="0.7">
      <stop offset="0" stop-color="{t['glow2']}" stop-opacity="{t['glow_op']}"/>
      <stop offset="1" stop-color="{t['glow2']}" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="keytop" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="{t['key_top']}"/>
      <stop offset="1" stop-color="{t['key_bot']}"/>
    </linearGradient>
    <pattern id="dots" width="28" height="28" patternUnits="userSpaceOnUse">
      <circle cx="2" cy="2" r="1.6" fill="{t['dot']}" fill-opacity="{t['dot_op']}"/>
    </pattern>{MARK_DEFS}</defs>
  <rect width="{w}" height="{h}" fill="{t['bg']}"/>
  <rect width="{w}" height="{h}" fill="url(#dots)"/>
  <rect width="{w}" height="{h}" fill="url(#glowA)"/>
  <rect width="{w}" height="{h}" fill="url(#glowB)"/>
"""


def chips(x, y, items, t, size=20):
    out, cx = [], x
    for item in items:
        w = len(item) * size * 0.56 + 36
        out.append(
            f'  <rect x="{cx:.0f}" y="{y}" width="{w:.0f}" height="{size * 1.75:.0f}" rx="{size * 0.875:.0f}" '
            f'fill="{t["chip_bg"]}" stroke="{t["border"]}"/>'
        )
        out.append(
            f'  <text x="{cx + w / 2:.0f}" y="{y + size * 1.22:.0f}" text-anchor="middle" font-family="{UI_FONT}" '
            f'font-size="{size}" font-weight="500" fill="{t["text"]}">{item}</text>'
        )
        cx += w + 12
    return "\n".join(out) + "\n"


def svg(w, h, label, body):
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" '
        f'role="img" aria-label="{label}">\n<!-- Generated by docs/brand/compose.py; edit that. -->\n{body}</svg>\n'
    )


# (x, y, label, tilt, accent, font size)
BANNER_KEYS = [
    (1075, 150, "esc", -8, False, 36), (1215, 128, "{", 4, False, 56),
    (1350, 150, "}", 10, False, 56), (1468, 172, ";", -10, False, 52),
    (1120, 292, "ctrl", -4, False, 34), (1262, 276, "-&gt;", 6, True, 46),
    (1404, 300, "ệ", -6, False, 52), (1180, 430, "tab", 8, False, 36),
    (1325, 426, "⌫", -5, False, 44),
]
SOCIAL_KEYS = [
    (895, 170, "esc", -8, False, 36), (1035, 150, "{", 4, False, 56),
    (1168, 175, "}", 10, False, 56), (940, 320, "ctrl", -4, False, 34),
    (1082, 304, "-&gt;", 6, True, 46), (1205, 330, "ệ", -6, False, 52),
    (1000, 465, "tab", 8, False, 36), (1145, 462, "⌫", -5, False, 44),
]


def main():
    for name, t in THEMES.items():
        title = f'font-family="{UI_FONT}" font-weight="750" letter-spacing="-2" fill="{t["title"]}"'
        body = f'font-family="{UI_FONT}" font-weight="400" fill="{t["text"]}"'

        banner = background(1600, 560, t) + mark(96, 104, 176)
        banner += f'  <text x="96" y="392" font-size="96" {title}>Super Keyboard</text>\n'
        banner += f'  <text x="98" y="458" font-size="32" {body}>{TAGLINE}</text>\n'
        banner += chips(98, 488, CHIPS, t)
        banner += "".join(keycap(x, y, l, t, r, a, f) for x, y, l, r, a, f in BANNER_KEYS)
        (SRC / f"banner-{name}.svg").write_text(svg(1600, 560, f"Super Keyboard: {TAGLINE}", banner))

        social = background(1280, 640, t) + mark(80, 90, 150)
        social += f'  <text x="80" y="345" font-size="88" {title}>Super Keyboard</text>\n'
        social += f'  <text x="82" y="404" font-size="30" {body}>The on-screen keyboard for</text>\n'
        social += f'  <text x="82" y="444" font-size="30" {body}>people who write code.</text>\n'
        social += chips(82, 486, CHIPS[:4], t)
        social += f'  <text x="82" y="590" font-family="{CODE_FONT}" font-size="22" fill="{t["muted"]}">{REPO}</text>\n'
        social += "".join(keycap(x, y, l, t, r, a, f) for x, y, l, r, a, f in SOCIAL_KEYS)
        (SRC / f"social-{name}.svg").write_text(svg(1280, 640, f"Super Keyboard: {TAGLINE}", social))

        lockup = f"  <defs>{MARK_DEFS}</defs>\n" + mark(0, 8, 224)
        lockup += f'  <text x="250" y="150" font-size="104" {title.replace("-2", "-2.5")}>Super Keyboard</text>\n'
        (SRC / f"lockup-{name}.svg").write_text(svg(1040, 240, "Super Keyboard", lockup))
    kinds = ("banner", "social", "lockup")
    print("wrote", ", ".join(f"src/{k}-{n}.svg" for k in kinds for n in THEMES))


if __name__ == "__main__":
    main()
